-- BD2 - S03 Manejo de Excepciones y Robustez
-- Script completo y listo para ejecutar (ver explicacion en
-- docs/bd2/sesiones/S03_Excepciones_Robustez.md, seccion 3).
--
-- Requisito: haber ejecutado antes S01_01_esquemas.sql, S01_02_tablas.sql,
-- S01_03_plsql.sql y S02_triggers_dml_auditoria.sql (este script reemplaza
-- SP_REGISTRAR_PRODUCTO y SP_APLICAR_DESCUENTO_PRODUCTO de S1, y crea
-- LOG_ERRORES y FN_OBTENER_PRECIO_PRODUCTO).
--
-- Ejecutar con una cuenta DBA (ej. system), igual que los scripts de S1 y
-- S2: todos los nombres estan calificados con BOM_CATALOGO. Conectado como
-- BOM_CATALOGO fallaria la creacion de LOG_ERRORES con ORA-01031, porque
-- ese usuario no tiene CREATE SEQUENCE y la columna ID_LOG es IDENTITY.

-- ============================================================
-- 1) Tabla de registro de errores
--    Sin FOREIGN KEY: un error debe poder registrarse aunque la
--    operacion que fallo nunca haya llegado a escribir nada.
-- ============================================================
CREATE TABLE BOM_CATALOGO.LOG_ERRORES (
    ID_LOG          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OBJETO          VARCHAR2(60) NOT NULL,
    CODIGO_ERROR    NUMBER,
    MENSAJE_ERROR   VARCHAR2(500),
    FECHA_EVENTO    TIMESTAMP DEFAULT SYSTIMESTAMP,
    USUARIO_ORACLE  VARCHAR2(30) DEFAULT USER
);

-- ============================================================
-- 2) SP_REGISTRAR_PRODUCTO: captura ORA-02291 (categoria inexistente)
--    con PRAGMA EXCEPTION_INIT, registra y relanza con mensaje claro.
--    SQLCODE y SQLERRM se copian antes a variables locales: no se
--    pueden usar directo dentro de un INSERT (ORA-00984).
-- ============================================================
CREATE OR REPLACE PROCEDURE BOM_CATALOGO.SP_REGISTRAR_PRODUCTO(
    p_id_categoria IN NUMBER,
    p_nombre IN VARCHAR2,
    p_precio IN NUMBER,
    p_stock IN NUMBER,
    p_id_producto OUT NUMBER
) IS
    e_categoria_inexistente EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_categoria_inexistente, -2291);
    v_codigo  NUMBER;
    v_mensaje VARCHAR2(500);
BEGIN
    INSERT INTO BOM_CATALOGO.PRODUCTOS (ID_CATEGORIA, NOMBRE, PRECIO, STOCK)
    VALUES (p_id_categoria, p_nombre, p_precio, p_stock)
    RETURNING ID INTO p_id_producto;
EXCEPTION
    WHEN e_categoria_inexistente THEN
        v_codigo  := SQLCODE;
        v_mensaje := SUBSTR(SQLERRM, 1, 500);
        INSERT INTO BOM_CATALOGO.LOG_ERRORES (OBJETO, CODIGO_ERROR, MENSAJE_ERROR)
        VALUES ('SP_REGISTRAR_PRODUCTO', v_codigo, v_mensaje);
        RAISE_APPLICATION_ERROR(-20010, 'La categoria ' || p_id_categoria || ' no existe. Verifica el id antes de registrar el producto.');
END;
/

-- ============================================================
-- 3) SP_APLICAR_DESCUENTO_PRODUCTO: excepcion propia con
--    RAISE_APPLICATION_ERROR (porcentaje fuera de [0, 100])
-- ============================================================
CREATE OR REPLACE PROCEDURE BOM_CATALOGO.SP_APLICAR_DESCUENTO_PRODUCTO(
    p_precio IN OUT NUMBER,
    p_porcentaje_descuento IN NUMBER
) IS
BEGIN
    IF p_porcentaje_descuento < 0 OR p_porcentaje_descuento > 100 THEN
        INSERT INTO BOM_CATALOGO.LOG_ERRORES (OBJETO, CODIGO_ERROR, MENSAJE_ERROR)
        VALUES ('SP_APLICAR_DESCUENTO_PRODUCTO', -20011, 'Porcentaje fuera de rango: ' || p_porcentaje_descuento);
        RAISE_APPLICATION_ERROR(-20011, 'El porcentaje de descuento debe estar entre 0 y 100. Recibido: ' || p_porcentaje_descuento);
    END IF;

    p_precio := p_precio - (p_precio * p_porcentaje_descuento / 100);
END;
/

-- ============================================================
-- 4) FN_OBTENER_PRECIO_PRODUCTO: funcion nueva, captura NO_DATA_FOUND
--    (excepcion predefinida). Como escribe en LOG_ERRORES, se invoca
--    desde un bloque PL/SQL, no dentro de un SELECT (ORA-14551).
-- ============================================================
CREATE OR REPLACE FUNCTION BOM_CATALOGO.FN_OBTENER_PRECIO_PRODUCTO(
    p_id_producto IN NUMBER
) RETURN NUMBER IS
    v_precio NUMBER;
    v_codigo NUMBER;
BEGIN
    SELECT PRECIO INTO v_precio
    FROM BOM_CATALOGO.PRODUCTOS
    WHERE ID = p_id_producto;

    RETURN v_precio;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        v_codigo := SQLCODE;
        INSERT INTO BOM_CATALOGO.LOG_ERRORES (OBJETO, CODIGO_ERROR, MENSAJE_ERROR)
        VALUES ('FN_OBTENER_PRECIO_PRODUCTO', v_codigo, 'Producto no encontrado: ' || p_id_producto);
        RAISE_APPLICATION_ERROR(-20012, 'No existe un producto con id ' || p_id_producto);
END;
/
