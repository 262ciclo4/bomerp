-- ============================================================
-- 6) Consulta reescrita (buena practica SQL) y EXPLAIN PLAN final
--    (conectado como BOMERP_APP)
--    Mismo resultado que 4)/5) - "ultimos 30 dias" - pero sin
--    envolver la columna FECHA en una funcion.
