-- BD2 - S04 Optimizacion de Consultas SQL
-- Paso 2: tablas de ventas, propiedad de BOM_VENTAS.
-- Requiere haber ejecutado antes S04_01_esquemas.sql.

CREATE TABLE BOM_VENTAS.VENTAS (
    ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA   TIMESTAMP NOT NULL,
    ESTADO  VARCHAR2(20) NOT NULL,
    TOTAL   NUMBER(12,2) NOT NULL,
    CONSTRAINT CK_VENTA_TOTAL CHECK (TOTAL >= 0)
);

CREATE TABLE BOM_VENTAS.DETALLE_VENTAS (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA         NUMBER NOT NULL,
    ID_PRODUCTO      NUMBER NOT NULL,
    NOMBRE_PRODUCTO  VARCHAR2(120) NOT NULL,
    PRECIO_UNITARIO  NUMBER(10,2) NOT NULL,
    CANTIDAD         NUMBER(10) NOT NULL,
    SUBTOTAL         NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (ID_VENTA)
        REFERENCES BOM_VENTAS.VENTAS(ID),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

-- Nota: ID_PRODUCTO NO lleva FOREIGN KEY hacia BOM_CATALOGO.PRODUCTOS,
-- a proposito (ver guia, 2.2) - el mismo criterio de separacion por
-- esquema que LP2 aplica a nivel de modulo Java con @NamedInterface.

-- BOMERP_APP ejecuta el backend de LP2, pero no es propietario de los objetos.
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_VENTAS.VENTAS TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_VENTAS.DETALLE_VENTAS TO BOMERP_APP;
